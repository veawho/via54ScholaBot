package schola

import (
	"fmt"
	"html"
	"strings"
)

// RenderMarkdown 将研究报告渲染为 Markdown（中英双语诗意化模板）
func RenderMarkdown(r *ResearchReport) string {
	var b strings.Builder
	if r.Lang == "en" {
		b.WriteString("# " + r.Title + "\n\n")
		b.WriteString("> *In the long night of inquiry, every verified fact is a star.*\n\n")
	} else {
		b.WriteString("# " + r.Title + "\n\n")
		b.WriteString("> 在求索的长夜里，每一则被证实的证据，都是一颗星。\n\n")
	}
	if r.Summary != "" {
		b.WriteString("## " + heading(r.Lang, "摘要", "Summary") + "\n\n")
		b.WriteString(r.Summary + "\n\n")
	}
	for _, s := range r.Sections {
		b.WriteString("## " + s.Heading + "\n\n")
		b.WriteString(s.Body + "\n\n")
	}
	if len(r.Evidence) > 0 {
		b.WriteString("## " + heading(r.Lang, "全部证据", "All Evidence") + "\n\n")
		for i, h := range r.Evidence {
			b.WriteString(fmt.Sprintf("%d. %s — %s (%s, %s)\n", i+1, h.Title, h.Source, h.Year, h.Venue))
		}
	}
	b.WriteString("\n---\n*Generated by via54ScholaBot · " + r.GeneratedAt.Format("2006-01-02 15:04") + "*\n")
	return b.String()
}

// RenderHTML 将研究报告渲染为 HTML 文档
func RenderHTML(r *ResearchReport) string {
	md := RenderMarkdown(r)
	langAttr := "zh-CN"
	if r.Lang == "en" {
		langAttr = "en"
	}
	body := html.EscapeString(md)
	return `<!DOCTYPE html>
<html lang="` + langAttr + `">
<head>
<meta charset="utf-8">
<title>` + html.EscapeString(r.Title) + `</title>
<style>
body{max-width:860px;margin:2rem auto;padding:0 1.2rem;font-family:"Segoe UI","Noto Serif SC",serif;line-height:1.75;color:#1a1a2e}
h1{border-bottom:2px solid #d4af37;padding-bottom:.5rem}
blockquote{border-left:4px solid #d4af37;color:#555;padding-left:1rem;font-style:italic}
h2{color:#8a5a00;margin-top:2rem}
code{background:#f5f5f5;padding:0 .3rem}
</style>
</head>
<body>
<pre style="white-space:pre-wrap;font-family:inherit">` + body + `</pre>
</body>
</html>`
}

func heading(lang, zh, en string) string {
	if lang == "en" {
		return en
	}
	return zh
}
